#!/usr/bin/env python3
"""Regenerate LIBRARY.md: a complete index of every study document in the repo.

Run from the repo root:  python3 scripts/make_library.py
Lists every tracked .md, .pdf and .html file (code READMEs included), grouped by
folder, with the title taken from the file itself. Re-run after adding material.
"""
import html
import os
import re
import subprocess
from collections import OrderedDict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

# Display order and names for the top-level sections.
SECTIONS = OrderedDict([
    ("(root)", "Challenges 01–41 (numbered notes)"),
    ("33-mmu-smmu", "33 · MMU & SMMUv3 kit"),
    ("35-gic", "35 · GIC interrupt controller kit"),
    ("41-gpio-core-pinmux", "41 · GPIO core & pinmux kit"),
    ("cpu-lab", "CPU lab (OOO core, pq5, YARP, RTL ladder)"),
    ("riscv-soc-design", "RISC-V SoC Design book notes + CPU-from-scratch"),
    ("hpca", "HPCA course (lecture notes + flash sheets)"),
    ("cache-coherence", "Cache coherence & memory consistency"),
    ("coresight", "CoreSight debug & trace"),
    ("aligner-uvm-course", "Aligner UVM course (notes, Q&A, project)"),
    ("sv-course-sessions", "SystemVerilog course sessions"),
    ("axi-interview-prep", "AXI interview prep"),
    ("uart-dv-pack", "UART DV pack"),
])

SKIP = {"LIBRARY.md"}


def tracked_docs():
    out = subprocess.check_output(["git", "-C", ROOT, "ls-files"], text=True)
    return [f for f in out.split("\n")
            if f.endswith((".md", ".pdf", ".html")) and f not in SKIP]


def title_of(path):
    full = os.path.join(ROOT, path)
    name = os.path.splitext(os.path.basename(path))[0].replace("-", " ").replace("_", " ")
    try:
        if path.endswith(".md"):
            with open(full, encoding="utf-8", errors="ignore") as fh:
                for line in fh:
                    m = re.match(r"#\s+(.+)", line)
                    if m:
                        return m.group(1).strip()
        elif path.endswith(".html"):
            with open(full, encoding="utf-8", errors="ignore") as fh:
                m = re.search(r"<title>(.*?)</title>", fh.read(20000), re.S | re.I)
                if m and m.group(1).strip():
                    return html.unescape(" ".join(m.group(1).split()))
    except OSError:
        pass
    return name


def kind_of(path):
    if path.endswith(".pdf"):
        return "PDF"
    if path.endswith(".html"):
        return "HTML"
    return "notes"


def size_of(path):
    n = os.path.getsize(os.path.join(ROOT, path))
    return f"{n / 1e6:.1f} MB" if n >= 1e6 else f"{max(1, round(n / 1e3))} KB"


def main():
    docs = tracked_docs()
    groups = OrderedDict((k, []) for k in SECTIONS)
    other = []
    for d in docs:
        top = d.split("/")[0] if "/" in d else "(root)"
        (groups[top] if top in groups else other).append(d)

    lines = [
        "# Library: every document in this repo",
        "",
        "Generated by `scripts/make_library.py`; re-run it after adding material.",
        "For a guided order, use [START-HERE.md](START-HERE.md). For everything as one download, use the",
        "[latest release](../../releases/latest) (`DV-interview-prep-all.zip`, or `…-docs-only.zip` for notes, PDFs and HTML only).",
        "",
        "> GitHub shows `.html` files as source. Download the release zip and open them in a browser.",
        "",
    ]
    total = 0
    counts = {"notes": 0, "PDF": 0, "HTML": 0}
    body = []
    toc = []
    for key, items in list(groups.items()) + ([("other", other)] if other else []):
        if not items:
            continue
        name = SECTIONS.get(key, "Other")
        anchor = re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")
        toc.append(f"- [{name}](#{anchor}) ({len(items)})")
        body += [f"## {name}", "", "| Document | Type | Size | Path |", "|---|---|---|---|"]
        for d in sorted(items):
            k = kind_of(d)
            counts[k] += 1
            total += 1
            t = title_of(d).replace("|", "\\|")
            body.append(f"| [{t}]({d}) | {k} | {size_of(d)} | `{d}` |")
        body.append("")
    lines += [f"**{total} documents:** {counts['notes']} notes, {counts['PDF']} PDFs, "
              f"{counts['HTML']} HTML pages.", ""]
    lines += toc + [""] + body
    with open(os.path.join(ROOT, "LIBRARY.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"LIBRARY.md: {total} documents")


if __name__ == "__main__":
    main()
